const block = (x, bottom, w, h, material, extra = {}) => ({
  x,
  y: bottom - h / 2,
  w,
  h,
  material,
  angle: extra.angle || 0,
  ...(extra.scale ? { scale: extra.scale } : {}),
  ...(extra.tag ? { tag: extra.tag } : {}),
});

